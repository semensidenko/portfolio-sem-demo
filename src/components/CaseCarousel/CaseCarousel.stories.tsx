const description = `
**Що це.** Карусель кейсів на першому екрані: картки **CaseCard** в один ряд, крапки для перемикання внизу ліворуч.

**Параметри (пропси) і значення за замовчуванням**

| Пропс | Значення | За замовчуванням |
| --- | --- | --- |
| \`cases\` | список карток (ті самі пропси, що в **CaseCard**) | — |
| \`label\` | назва каруселі для скрінрідера | «Кейси» |
| \`autoplayMs\` | автозміна кейса, мс; \`0\` — вимкнено | \`5000\` |

**Як поводиться** (як у старому макеті)

- **комп'ютер** (від \`desk\`, 1100px) — видно дві картки з проміжком 20px макета, **телефон і планшет** — одну (проміжок 12px). Крок — одна картка.
- **Безкінечна прокрутка** — після останнього кейса йде перший без «перемотки» назад (у кінці треку стоять копії перших карток, невидимі для скрінрідера й клавіатури). Перехід — 0,6 с з кривою \`ease-glide\`.
- **Автозміна** — кожні 5 с на наступний кейс. Пауза, поки курсор над каруселлю, фокус усередині або вкладка прихована. Після ручного гортання таймер починається спочатку. Якщо в системі вимкнено анімації, автозміни немає.
- **Гортання** — свайп, перетягування мишею, трекпад, колесо з Shift, крапки; картки «примагнічуються» до краю. Після перетягування картка не відкривається.
- **Крапки** — по одній на кожен кейс (три й на комп'ютері, як у старому макеті), розмір 10px з кроком 18px. Активна — повна й більша, інші напівпрозорі. Кожна крапка — кнопка з назвою «Показати кейс N» і \`aria-current\` для активної. Фокус: контур \`accent\`.
- **Пауза** — маленька кнопка ⏸ / ▶ одразу після крапок зупиняє й вмикає автозміну (\`aria-pressed\`).
- Якщо в системі вимкнено анімації, перехід по крапці миттєвий.

**Доступність.** Автозміну можна зупинити кнопкою паузи (WCAG 2.2.2); наведення й фокус теж ставлять її на паузу. Крапки, як у старому макеті, стоять щільно: зона натискання кожної 18×26px, трохи менша за рекомендовані 24px.

**Токени:** кольори \`canvas\` (крапки), \`accent\` (фокус); радіус \`rounded-control\`; відступи 2 (крапки й проміжок між картками 2 + 2).

**Коли використовувати.** На першому екрані, щоб показати 2–4 кейси в обмеженому місці.

**Коли ні.** Для повного списку робіт (там сітка карток). Для одного кейса.

**Як брати в код**

\`\`\`tsx
import { CaseCarousel } from "@/components/CaseCarousel/CaseCarousel";
import { heroCases } from "@/content/cases";

<CaseCarousel cases={heroCases} />
\`\`\`

Перевірити телефон: кнопка **Viewport** (іконка монітора) у верхній панелі Storybook.
`;

